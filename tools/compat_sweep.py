#!/usr/bin/env python3
"""Classify the most-used GitHub Actions by what a runner must provide.

The question this answers: can a small, fast runner image execute the actions
people actually use? For each action we fetch its action.yml and read
`runs.using`, which is the hard requirement — node20 means a Node runtime must
exist, docker means a container runtime must exist, composite means the steps'
own dependencies decide.

    python3 tools/compat_sweep.py [--out docs/compatibility.md]
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.request
from collections import Counter
from pathlib import Path

# Actions ranked by marketplace usage (approximate, sampled from marketplace
# "most installed" plus the ones that appear in nearly every workflow).
ACTIONS = [
    "actions/checkout@v4",
    "actions/setup-node@v4",
    "actions/setup-python@v5",
    "actions/cache@v4",
    "actions/upload-artifact@v4",
    "actions/download-artifact@v4",
    "actions/setup-java@v4",
    "actions/setup-go@v5",
    "actions/setup-dotnet@v4",
    "actions/github-script@v7",
    "docker/build-push-action@v6",
    "docker/login-action@v3",
    "docker/setup-buildx-action@v3",
    "docker/setup-qemu-action@v3",
    "docker/metadata-action@v5",
    "github/codeql-action/init@v3",
    "softprops/action-gh-release@v2",
    "peter-evans/create-pull-request@v6",
    "aws-actions/configure-aws-credentials@v4",
    "hashicorp/setup-terraform@v3",
    "dorny/paths-filter@v3",
    "codecov/codecov-action@v4",
    "google-github-actions/auth@v2",
    "azure/login@v2",
    "actions/stale@v9",
]

RAW = "https://raw.githubusercontent.com/{repo}/{ref}/{path}"


def fetch_action_yml(repo: str, ref: str) -> str | None:
    for name in ("action.yml", "action.yaml"):
        try:
            with urllib.request.urlopen(RAW.format(repo=repo, ref=ref, path=name), timeout=20) as r:
                return r.read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            if e.code != 404:
                return None
        except Exception:
            return None
    return None


def classify(repo: str, ref: str) -> dict:
    text = fetch_action_yml(repo, ref)
    if text is None:
        return {"repo": repo, "using": "unavailable", "needs": ["?"], "note": "action.yml not found"}
    using = "unknown"
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("using:"):
            using = stripped.split(":", 1)[1].strip().strip("'\"")
            break
    needs = []
    note = ""
    if using.startswith("node"):
        needs.append(using)
        # setup-* actions download a toolchain at runtime: they need network,
        # tar, and checksum tooling as well as node.
        if "/setup-" in repo:
            needs += ["network", "tar", "sha256"]
            note = "downloads a toolchain at runtime"
        if "codeql" in repo:
            needs += ["network", "extraction"]
            note = "downloads the CodeQL bundle"
    elif using == "docker":
        needs += ["container runtime", "network(pull)"]
        note = "runs its own image"
    elif using == "composite":
        needs += ["steps' own deps"]
        note = "composite: requirements are transitive"
    return {"repo": repo, "using": using, "needs": needs, "note": note}


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("docs/compatibility.md"))
    args = ap.parse_args(argv)

    results = []
    for spec in ACTIONS:
        repo, _, ref = spec.partition("@")
        # Sub-actions like github/codeql-action/init use the parent repo's action.yml.
        parts = repo.split("/")
        if len(parts) > 2:
            repo = "/".join(parts[:2])
        result = classify(repo, ref or "main")
        result["spec"] = spec
        results.append(result)
        print(f"{spec:52} {result['using']:10} {' '.join(result['needs'])}", flush=True)

    counts = Counter(r["using"].split("@")[0] for r in results)
    node_share = sum(v for k, v in counts.items() if k.startswith("node")) / len(results)
    print("\nsummary:", dict(counts))
    print(f"node-based share: {node_share:.0%}")

    rows = "\n".join(
        f"| `{r['spec']}` | {r['using']} | {', '.join(r['needs']) or '—'} | {r['note'] or ''} |"
        for r in results
    )
    doc = f"""# Action compatibility

Generated by `tools/compat_sweep.py`. Each row is the action's own `action.yml`
`runs.using` value, which is the requirement a runner has to satisfy.

| Action | requires | runtime needs | note |
| --- | --- | --- | --- |
{rows}

## What this means

{sum(v for k, v in counts.items() if k.startswith('node'))} of {len(results)} actions ({node_share:.0%}) declare `node20`.

A runner that provides `/bin/sh`, `git`, a Node 20 runtime, `tar`, `sha256sum` and
network egress runs most of the marketplace. The Docker actions are Node wrappers
that call the `docker` CLI, so they need the CLI and access to a daemon rather than
a daemon inside the runner.

The `setup-*` actions download their toolchain at runtime, so nothing has to be
baked into the image. That is what keeps the base runner small.
"""
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(doc)
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
